"""Generate a Process Definition Document .docx from a session +
canonical step set. Uses python-docx. Mirrors the team's existing
PDD format.
"""

from __future__ import annotations
import logging
from datetime import datetime, timezone
from pathlib import Path

try:
    from docx import Document
    from docx.shared import Pt, Inches
except ImportError:
    Document = None
    Pt = None
    Inches = None

logger = logging.getLogger(__name__)


def write_pdd(
    out_path: Path,
    *,
    session_folder: Path,
    canonical: dict | None,
    annotations: dict,
    stats: dict,
    manifest: dict,
    analysis: dict | None = None,
) -> None:
    if Document is None:
        raise RuntimeError(
            "python-docx is not installed. Add `python-docx>=1.1.0` to "
            "normalization/requirements.txt and reinstall."
        )

    doc = Document()
    doc.add_heading("Process Definition Document", level=0)
    eng = manifest.get("engagement_id") or "Engagement"
    doc.add_paragraph(f"Engagement: {eng}")
    worker_id = (manifest.get("config", {}).get("worker") or {}).get("id", "-")
    doc.add_paragraph(f"Worker: {worker_id}")
    doc.add_paragraph(f"Captured: {manifest.get('started_at', '-')}")
    doc.add_paragraph(f"Generated: {datetime.now(timezone.utc).strftime('%Y-%m-%d')}")

    if canonical:
        doc.add_heading(f"Process: {canonical.get('name', '-')}", level=1)
        doc.add_paragraph(f"Canonical version: {canonical.get('version', '-')}")

    # Analysis-layer context (Cluster N / ADR-0008). analysis.json is
    # absent on sessions normalized before the analysis layer existed;
    # the per-step enrichment is simply skipped when it is.
    analysis = analysis or {}
    waste_by_step = {
        w["step_id"]: w
        for w in (analysis.get("waste_classification") or [])
        if w.get("step_id")
    }
    auto_by_step = {
        a["step_id"]: a
        for a in (analysis.get("automation_candidates") or [])
        if a.get("step_id")
    }
    efficiency = analysis.get("efficiency") or {}

    # Executive summary up front -- the headline figures a stakeholder reads
    # before the step-by-step body.
    _write_overview(doc, stats=stats, manifest=manifest, efficiency=efficiency)

    # Phase-by-phase narrative
    phases = annotations.get("phases", []) or []
    steps = annotations.get("steps", []) or []
    step_by_id = {s["step_id"]: s for s in steps}

    if phases:
        for phase in phases:
            doc.add_heading(phase["name"], level=2)
            if phase.get("description"):
                doc.add_paragraph(phase["description"])
            contained = [step_by_id.get(sid) for sid in (phase.get("step_ids") or [])]
            contained = [s for s in contained if s]
            for step in contained:
                _write_step(doc, step, session_folder, waste_by_step, auto_by_step)
    elif steps:
        doc.add_heading("Steps", level=1)
        for step in steps:
            _write_step(doc, step, session_folder, waste_by_step, auto_by_step)
    else:
        doc.add_paragraph("No steps have been annotated for this session yet.")

    # Statistics table
    if stats and stats.get("activity_stats"):
        doc.add_heading("Activity statistics", level=1)
        table = doc.add_table(rows=1, cols=4)
        hdr = table.rows[0].cells
        hdr[0].text = "Activity"
        hdr[1].text = "Frequency"
        hdr[2].text = "Total time"
        hdr[3].text = "Median"
        for row in stats["activity_stats"][:25]:
            r = table.add_row().cells
            r[0].text = str(row["activity_label"])
            r[1].text = str(row["frequency"])
            r[2].text = _fmt_ms(row.get("total_duration_ms", 0))
            r[3].text = _fmt_ms(row.get("median_ms", 0))
        if len(stats["activity_stats"]) > 25:
            note = doc.add_paragraph(
                f"Showing 25 of {len(stats['activity_stats'])} activities."
            )
            for run in note.runs:
                run.italic = True

    footer = doc.add_paragraph(
        "Generated by the Process Discovery Viewer on "
        f"{datetime.now(timezone.utc).strftime('%Y-%m-%d')}."
    )
    for run in footer.runs:
        run.italic = True
        if Pt is not None:
            run.font.size = Pt(9)

    doc.save(str(out_path))


def _write_overview(doc, *, stats, manifest, efficiency):
    """An executive-summary block: a one-line orientation, the headline figures,
    and where the captured time went. Every row is guarded, so a session
    normalized before a given statistic existed simply omits that row instead of
    erroring."""
    stats = stats or {}
    meta = stats.get("meta") or {}
    case_stats = stats.get("case_stats") or []
    activity_stats = stats.get("activity_stats") or []

    rows = []
    case_count = meta.get("case_count")
    if case_count is None and case_stats:
        case_count = len(case_stats)
    if case_count is not None:
        durs = [c.get("active_ms") or c.get("wall_clock_ms") for c in case_stats]
        durs = [d for d in durs if d]
        if durs:
            rows.append(("Cases observed",
                         f"{case_count} (avg {_fmt_ms(sum(durs) / len(durs))} each)"))
        else:
            rows.append(("Cases observed", str(case_count)))

    step_count = meta.get("step_count")
    sb = meta.get("step_state_breakdown") or {}
    if step_count is not None:
        auto = (sb.get("auto_suggested", 0) or 0) + (sb.get("auto_matched", 0) or 0)
        confirmed = (sb.get("manually_authored", 0) or 0) + (sb.get("edited", 0) or 0)
        rows.append(("Steps", f"{step_count} ({auto} auto-detected, {confirmed} confirmed)"))

    if meta.get("phase_count"):
        rows.append(("Phases", str(meta["phase_count"])))
    if activity_stats:
        rows.append(("Distinct activities", str(len(activity_stats))))
    if efficiency.get("process_efficiency_ratio") is not None:
        pct = round(efficiency["process_efficiency_ratio"] * 100)
        rows.append(("Process efficiency", f"{pct}% value-add (heuristic estimate)"))

    if not rows and not activity_stats:
        return

    doc.add_heading("Overview", level=1)
    captured = manifest.get("started_at")
    worker = (manifest.get("config", {}).get("worker") or {}).get("id")
    when = f" captured {captured}" if captured and captured != "-" else ""
    who = f" by {worker}" if worker and worker != "-" else ""
    if when or who:
        doc.add_paragraph(f"Reconstructed from the recorded session{when}{who}.")

    if rows:
        t = doc.add_table(rows=0, cols=2)
        for k, v in rows:
            cells = t.add_row().cells
            cells[0].text = k
            cells[1].text = str(v)

    # Where the captured time went -- the top activities by total duration.
    timed = sorted(
        (a for a in activity_stats if a.get("total_duration_ms")),
        key=lambda a: a["total_duration_ms"], reverse=True,
    )
    total = sum(a.get("total_duration_ms", 0) for a in activity_stats)
    if timed:
        doc.add_heading("Where the time went", level=2)
        tt = doc.add_table(rows=1, cols=3)
        h = tt.rows[0].cells
        h[0].text, h[1].text, h[2].text = "Activity", "Share", "Time"
        for a in timed[:8]:
            r = tt.add_row().cells
            r[0].text = str(a.get("activity_label", "-"))
            r[1].text = f"{round(a['total_duration_ms'] / total * 100)}%" if total else "-"
            r[2].text = _fmt_ms(a.get("total_duration_ms", 0))


def _write_step(doc, step, session_folder, waste_by_step=None, auto_by_step=None):
    doc.add_heading(step["name"], level=3)
    if step.get("description"):
        doc.add_paragraph(step["description"])
    for ref in (step.get("evidence", {}).get("screenshot_refs") or []):
        full = session_folder / ref
        if full.exists():
            try:
                doc.add_picture(str(full), width=Inches(4.5))
            except (FileNotFoundError, OSError, ValueError) as exc:
                logger.warning(
                    "pdd_export: skipping screenshot %s for step %s: %s",
                    ref, step.get("step_id", "?"), exc,
                )
    flags = [k for k, v in (step.get("flags") or {}).items() if v is True]
    if flags:
        labels = [_FLAG_LABELS.get(f, f.replace("_", " ").capitalize()) for f in flags]
        p = doc.add_paragraph(f"Flags: {', '.join(labels)}")
        for run in p.runs:
            run.italic = True

    # Analysis-layer context (Cluster N), when analysis.json was present.
    sid = step.get("step_id")
    waste = (waste_by_step or {}).get(sid)
    if waste:
        bits = []
        if waste.get("nva_ms"):
            bits.append(f"{_fmt_ms(waste['nva_ms'])} non-value-add")
        if waste.get("waste_types"):
            bits.append("waste types: " + ", ".join(waste["waste_types"]))
        if bits:
            p = doc.add_paragraph("Waste: " + "; ".join(bits))
            for run in p.runs:
                run.italic = True
    auto = (auto_by_step or {}).get(sid)
    if auto and auto.get("data_sufficiency") == "multi_instance":
        rep = (auto.get("scores") or {}).get("repetitiveness")
        if rep is not None:
            p = doc.add_paragraph(
                f"Automation potential: repetitiveness {round(rep * 100)}%"
            )
            for run in p.runs:
                run.italic = True


_FLAG_LABELS = {
    "waste": "Waste",
    "rework": "Rework",
    "automation_candidate": "Automation candidate",
    "value_add": "Value-add",
    "bottleneck": "Bottleneck",
}


def _fmt_ms(ms):
    if ms is None: return "-"
    s = ms / 1000
    if s < 60: return f"{s:.1f}s"
    if s < 3600: return f"{int(s // 60)}m {int(s % 60)}s"
    return f"{int(s // 3600)}h {int((s % 3600) // 60)}m"
